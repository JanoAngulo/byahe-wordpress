#!/usr/bin/env node
/**
 * Downloads the photos listed in scripts/photos.json, converts them to WebP
 * (longest edge 2000px, quality 78) into prototype/public/images/, and regenerates
 * CREDITS.md. Existing files are skipped unless --force is passed.
 */
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const photos = JSON.parse(readFileSync(resolve(root, 'scripts/photos.json'), 'utf8'));
const outDir = resolve(root, 'prototype/public/images');
const force = process.argv.includes('--force');

const LICENSES = {
  pexels: '[Pexels License](https://www.pexels.com/license/)',
  unsplash: '[Unsplash License](https://unsplash.com/license)',
};

const downloadUrl = (p) =>
  p.source === 'pexels'
    ? `https://images.pexels.com/photos/${p.id}/pexels-photo-${p.id}.jpeg?auto=compress&cs=tinysrgb&w=2400`
    : p.downloadUrl;

mkdirSync(outDir, { recursive: true });

for (const photo of photos) {
  const file = resolve(outDir, `${photo.slug}.webp`);
  if (existsSync(file) && !force) {
    console.log(`skip ${photo.slug}`);
    continue;
  }
  const res = await fetch(downloadUrl(photo));
  if (!res.ok) throw new Error(`Download failed for ${photo.slug}: HTTP ${res.status}`);
  const input = Buffer.from(await res.arrayBuffer());
  const info = await sharp(input)
    .resize({ width: 2000, height: 2000, fit: 'inside', withoutEnlargement: true })
    .webp({ quality: photo.quality ?? 78 })
    .toFile(file);
  console.log(`wrote ${photo.slug}.webp ${info.width}x${info.height} ${Math.round(info.size / 1024)}KB`);
}

const rows = photos.map((p) => {
  const who = p.photographer ?? 'Credited on the source page';
  return `| \`${p.slug}.webp\` | ${p.alt} | ${who} | [${p.source === 'pexels' ? 'Pexels' : 'Unsplash'} #${p.id}](${p.pageUrl}) | ${LICENSES[p.source]} |`;
});

writeFileSync(
  resolve(root, 'CREDITS.md'),
  `# Photo credits

Scene photography used in the BYAHE prototype and theme. All images are free stock photos used under their source license. They are resized and converted to WebP, and shown with a yellow and blue duotone treatment on the site.

| File | Shows | Photographer | Source | License |
|---|---|---|---|---|
${rows.join('\n')}

## Fonts

| Font | Designer | Source | License |
|---|---|---|---|
| Cubao Free (variable, width axis) | Aaron Amar | [aaronamar.gumroad.com](https://aaronamar.gumroad.com/l/cubaofreev2) | Free for personal and commercial use, per the designer |
| Inter | Rasmus Andersson | [@fontsource-variable/inter](https://fontsource.org/fonts/inter) | SIL Open Font License 1.1 |
| Space Grotesk | Florian Karsten | [@fontsource-variable/space-grotesk](https://fontsource.org/fonts/space-grotesk) | SIL Open Font License 1.1 |

Generated by \`scripts/fetch-photos.mjs\` from \`scripts/photos.json\`.
`,
);
console.log('wrote CREDITS.md');

const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/"/g, '&quot;');
const photoItems = photos.map((p) => {
  const source = p.source === 'pexels' ? 'Pexels' : 'Unsplash';
  const who = p.photographer ? `${esc(p.photographer)} on ` : '';
  return `      <li><span class="ui-strong">${esc(p.alt)}</span><br>${who}<a href="${p.pageUrl}">${source} #${p.id}</a>, ${source} License</li>`;
});
writeFileSync(
  resolve(root, 'prototype/partials/credits.html'),
  `<!-- Generated by scripts/fetch-photos.mjs from scripts/photos.json. Do not edit. -->
<div class="credits-grid">
  <div>
    <h3>Photos</h3>
    <ul class="credits-list">
${photoItems.join('\n')}
    </ul>
  </div>
  <div>
    <h3>Fonts</h3>
    <ul class="credits-list">
      <li><span class="ui-strong">Cubao Free</span><br>Aaron Amar, <a href="https://aaronamar.gumroad.com/l/cubaofreev2">aaronamar.gumroad.com</a>, free for personal and commercial use</li>
      <li><span class="ui-strong">Inter</span><br>Rasmus Andersson, <a href="https://fontsource.org/fonts/inter">Fontsource</a>, SIL Open Font License 1.1</li>
      <li><span class="ui-strong">Space Grotesk</span><br>Florian Karsten, <a href="https://fontsource.org/fonts/space-grotesk">Fontsource</a>, SIL Open Font License 1.1</li>
    </ul>
    <h3>Icons</h3>
    <ul class="credits-list">
      <li><span class="ui-strong">Lucide</span><br><a href="https://lucide.dev">lucide.dev</a>, ISC License</li>
    </ul>
  </div>
</div>
`,
);
console.log('wrote prototype/partials/credits.html');
