/**
 * Converts tokens/tokens.json into Tailwind v4 @theme CSS and theme.json settings.
 */

const titleCase = (slug) => slug.replace(/(^|-)(\w)/g, (_, sep, c) => (sep ? ' ' : '') + c.toUpperCase());

const fontStack = ({ family, fallback }) => `"${family}", ${fallback}`;

const round = (n, d = 4) => Math.round(n * 10 ** d) / 10 ** d;

/**
 * Fluid modular type scale (Utopia-style). Each step interpolates linearly from
 * min.base * min.ratio^step at minViewport to max.base * max.ratio^step at maxViewport.
 */
export function typeScale(tokens) {
  const { minViewport, maxViewport, min, max, steps, lineHeights } = tokens.typeScale;
  return Object.entries(steps).map(([name, step]) => {
    const minPx = round(min.base * min.ratio ** step, 2);
    const maxPx = round(max.base * max.ratio ** step, 2);
    const slope = (maxPx - minPx) / (maxViewport - minViewport);
    const interceptRem = round((minPx - slope * minViewport) / 16);
    const vw = round(slope * 100);
    return {
      name,
      minPx,
      maxPx,
      lineHeight: lineHeights[name],
      clamp: `clamp(${round(minPx / 16)}rem, ${interceptRem}rem + ${vw}vw, ${round(maxPx / 16)}rem)`,
    };
  });
}

export function toTailwindTheme(tokens) {
  const lines = [
    ...Object.entries(tokens.color).map(([n, v]) => `  --color-${n}: ${v};`),
    ...Object.entries(tokens.font).map(([n, f]) => `  --font-${n}: ${fontStack(f)};`),
    '  --text-*: initial;',
    ...typeScale(tokens).flatMap((s) => [`  --text-${s.name}: ${s.clamp};`, `  --text-${s.name}--line-height: ${s.lineHeight};`]),
    ...Object.entries(tokens.shadow).map(([n, v]) => `  --shadow-${n}: ${v};`),
    ...Object.entries(tokens.radius).map(([n, v]) => `  --radius-${n}: ${v};`),
    ...Object.entries(tokens.shadowOffset).map(([n, v]) => `  --shadow-offset-${n}: ${v};`),
  ];
  return `/* Generated by scripts/build-tokens.mjs. Do not edit. */\n@theme {\n${lines.join('\n')}\n}\n`;
}

const SIZE_NAMES = {
  sm: 'Small',
  base: 'Base',
  lg: 'Large',
  xl: 'Extra large',
};
const sizeName = (step) => SIZE_NAMES[step] ?? `${step.replace('xl', '')}× large`;

const fontFace = (family, file) => ({
  fontFamily: family,
  fontWeight: file.weight,
  fontStyle: 'normal',
  ...(file.stretch ? { fontStretch: file.stretch } : {}),
  fontDisplay: 'swap',
  src: [file.src],
});

export function toThemeJsonSettings(tokens) {
  return {
    color: {
      defaultPalette: false,
      defaultGradients: false,
      defaultDuotone: false,
      palette: Object.entries(tokens.color).map(([slug, color]) => ({ slug, name: titleCase(slug), color })),
      duotone: Object.entries(tokens.duotone).map(([slug, d]) => ({
        slug,
        name: d.name,
        colors: d.colors.map((c) => tokens.color[c]),
      })),
    },
    typography: {
      defaultFontSizes: false,
      fontFamilies: Object.entries(tokens.font).map(([slug, f]) => ({
        slug,
        name: f.family.replace(/ Variable$/, ''),
        fontFamily: fontStack(f),
        fontFace: (f.files ?? []).map((file) => fontFace(f.family, file)),
      })),
      fluid: false,
      fontSizes: typeScale(tokens).map((s) => ({ slug: s.name, name: sizeName(s.name), size: s.clamp })),
    },
    custom: {
      radius: tokens.radius,
      shadowOffset: tokens.shadowOffset,
    },
    spacing: {
      defaultSpacingSizes: false,
      spacingSizes: Object.entries(tokens.spacing).map(([slug, size]) => ({ slug, name: slug, size })),
    },
    shadow: {
      defaultPresets: false,
      presets: Object.entries(tokens.shadow).map(([slug, shadow]) => ({ slug, name: titleCase(slug), shadow })),
    },
  };
}
